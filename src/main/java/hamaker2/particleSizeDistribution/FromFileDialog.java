    private void loadDataIntoTable(File selectedFile) {
        try (BufferedReader input = new BufferedReader(new java.io.FileReader(selectedFile))) {
            
            m_tableData.load(input);
            
            
        } catch (IOException ex) {
            Logger.getLogger(FromFileDialog.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    private class FileTableModel extends AbstractTableModel {

        ArrayList<ArrayList<String>> m_data;
        
        public FileTableModel() {
            m_data = new ArrayList<>();
        }
        
        public void load(BufferedReader input) throws IOException {
            m_data.clear();
            while (input.ready()) {
                String line = input.readLine();
                String[] elements = line.split("\\s+");
                ArrayList<String> row = new ArrayList<>();
                row.addAll(Arrays.asList(elements));
                m_data.add(row);
                this.fireTableStructureChanged();
            }
        }
        
        @Override
        public int getRowCount() {
            return m_data.size();
        }

        @Override
        public int getColumnCount() {
            int max = 0;
            for (ArrayList<String> row : m_data) {
                max = Math.max(max, row.size());
            }
            return max + 1;
        }
        
        @Override
        public String getColumnName(int column) {
            if (column == 0) {
                return "Row";
            } else {
                return super.getColumnName(column-1);
            }
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
            if (rowIndex >= m_data.size()) {
                return "";
            } else {
                if (columnIndex == 0) {
                    return String.valueOf(rowIndex + 1);
                } else if (columnIndex > m_data.get(rowIndex).size()) {
                    return "";
                } else {
                    return m_data.get(rowIndex).get(columnIndex - 1);
                }
            }
        }
    }
        
