    private void o_loadButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_loadButtonActionPerformed
        int startRow = (int)o_startRow.getValue() - 1;
        int numPoints = m_tableData.getRowCount() - startRow;
        double[] diameters = new double[numPoints];
        double[] numberFractions = new double[numPoints];
        
        double cumm_prev = 0.0;
        double volFracSum = 0.0;
        
        for (int i=0;i<numPoints;i++) {
            //get the raw values
            String size_str = (String)m_tableData.getValueAt(i + startRow, o_sizeCol.getSelectedIndex() + 1);
            String freq_str = (String)m_tableData.getValueAt(i + startRow, o_freqCol.getSelectedIndex() + 1);
            double size = Double.parseDouble(size_str);
            double freq = Double.parseDouble(freq_str);
            
            //treat size type
            if (o_sizeType.getSelectedItem().equals("Diameter")) {
                //just keep it, it's already fine
            } else if (o_sizeType.getSelectedItem().equals("Radius")) {
                size *= 2;
            } else {
                System.out.println("Unknown size type: " + o_sizeType.getSelectedItem());
            }
            
            //treat size unit
            if (o_sizeUnit.getSelectedItem().equals("nm")) {
                size *= 1E-9;
            } else if (o_sizeUnit.getSelectedItem().equals("µm")) {
                size *= 1E-6;
            } else if (o_sizeUnit.getSelectedItem().equals("mm")) {
                size *= 1E-3;
            } else if (o_sizeUnit.getSelectedItem().equals("m")) {
                //just keep it, it's already fine
            } else {
                System.out.println("Unknown size unit: " + o_sizeUnit.getSelectedItem());
            }
            
            
            if (o_freqType.getSelectedItem().equals("Number")) {
                //just keep it, it's already fine
            } else if (o_freqType.getSelectedItem().equals("Cummulative number")) {
                //deduct previous fraction
                double temp = cumm_prev;
                cumm_prev = freq;
                freq -= temp;
            } else if (o_freqType.getSelectedItem().equals("Volume")) {
                //I still have to post multiply with the sum of all volume fractions, so accumulate it
                volFracSum += freq;
                //convert to number
                freq /= 4.0 / 3.0 * Math.PI * size * size * size / 8.0;
            } else if (o_freqType.getSelectedItem().equals("Cummulative volume")) {
                //deduct previous fraction
                double temp = cumm_prev;
                cumm_prev = freq;
                freq -= temp;
                //now I have the proper volume fraction, proceed as above
                //I still have to post multiply with the sum of all volume fractions, so accumulate it
                volFracSum += freq;
                //convert to number
                freq /= 4.0 / 3.0 * Math.PI * size * size * size / 8.0;
            } else {
                System.out.println("Unknown frequency type: " + o_freqType.getSelectedItem());
            }
                        
            diameters[i] = size;
            numberFractions[i] = freq;
        }
        
        //check if post fix is needed
        if (o_freqType.getSelectedItem().equals("Volume") || o_freqType.getSelectedItem().equals("Cummulative Volume")) {
            for (int i=0;i<numPoints;i++) {
                numberFractions[i] *= volFracSum;
            }
        }
                
        m_psdToEdit.setData(o_filePath.getText(), numPoints, diameters, numberFractions);
        
        this.setVisible(false);
    }//GEN-LAST:event_o_loadButtonActionPerformed

