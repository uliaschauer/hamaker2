    /**
     * Show the dialog for a given stability object and heterogeneity of the series
     * @param stability Stability object
     * @param heterogeneous Is the series heterogeneous
     */
    public void showForStability(Stability stability, boolean heterogeneous) {
        m_stability_to_edit = stability;
        m_heterogeneous = heterogeneous;
        
        if (m_heterogeneous) {
            o_p1_conc.setText(String.valueOf(m_stability_to_edit.getParticle1Concentration()));
            o_p2_conc.setText(String.valueOf(m_stability_to_edit.getParticle2Concentration()));
            o_p2_conc.setEnabled(true);
        } else {
            o_p1_conc.setText(String.valueOf(m_stability_to_edit.getParticle1Concentration()));
            o_p2_conc.setText(String.valueOf(0.00));
            o_p2_conc.setEnabled(false);
        }
        
        o_hours.setText(String.valueOf(m_stability_to_edit.getHours()));
        o_minutes.setText(String.valueOf(m_stability_to_edit.getMinutes()));
        o_viscous.setSelected(m_stability_to_edit.getViscous());
        
        setVisible(true);
    }
    
