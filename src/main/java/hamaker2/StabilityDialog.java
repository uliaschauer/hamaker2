    private void o_okActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_okActionPerformed
        if (m_heterogeneous) {
            m_stability_to_edit.setParticle1Concentration(Utils.StringToDouble(o_p1_conc.getText()));
            m_stability_to_edit.setParticle2Concentration(Utils.StringToDouble(o_p2_conc.getText()));
        }
        else
        {
            m_stability_to_edit.setParticle1Concentration(Utils.StringToDouble(o_p1_conc.getText()));
        }
        m_stability_to_edit.setHours(Integer.valueOf(o_hours.getText()).intValue());
        m_stability_to_edit.setMinutes(Integer.valueOf(o_minutes.getText()).intValue());
        m_stability_to_edit.setViscous(Boolean.valueOf(o_viscous.isSelected()).booleanValue());
        
        setVisible(false);
    }//GEN-LAST:event_o_okActionPerformed
    
