    private class MediumTableModel extends AbstractTableModel {

        @Override
        public int getColumnCount() {
            return 3;
        }

        @Override
        public int getRowCount() {
            if (m_mediumToEdit == null) {
                return 0;
            } else {
                return m_mediumToEdit.getNumElectrolyteComponents();
            }
        }

        @Override
        public String getColumnName(int column) {
            String names[] = {"Label", "Valence [e]", "Concentration [M]"};
            return names[column];
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
            switch (columnIndex) {
                case 0:
                    return m_mediumToEdit.getElectrolyteComponentLabel(rowIndex);
                case 1:
                    return m_mediumToEdit.getElectrolyteComponentValence(rowIndex);
                case 2:
                    return m_mediumToEdit.getElectrolyteComponentConcentration(rowIndex);
            }

            return "Error";
        }

        @Override
        public boolean isCellEditable(int row, int col) {
            return true;
        }

        @Override
        public void setValueAt(Object aValue, int rowIndex, int columnIndex) {
            switch (columnIndex) {
                case 0:
                    m_mediumToEdit.setElectrolyteComponentLabel(rowIndex, (String) aValue);
                    break;
                case 1:
                    m_mediumToEdit.setElectrolyteComponentValence(rowIndex, Utils.StringToDouble((String) aValue));
                    break;
                case 2:
                    m_mediumToEdit.setElectrolyteComponentConcentration(rowIndex, Utils.StringToDouble((String) aValue));
                    break;
            }

            updateKappa();
        }
    }
