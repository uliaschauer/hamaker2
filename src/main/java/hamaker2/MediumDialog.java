    private void o_okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_okButtonActionPerformed
        m_mediumToEdit.setDensityFromText(o_density.getText());
        m_mediumToEdit.setDielectricConstantFromText(o_dielectricConstant.getText());

        setVisible(false);
        m_mediumToEdit = null;
        m_saveMedium = null;
    }//GEN-LAST:event_o_okButtonActionPerformed

    private void o_cancelButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_cancelButtonActionPerformed

        //restore the electrolyte
        //first remove all that's there
        m_mediumToEdit.deleteAllElectrolyteComponents();
        //now copy in the saved ones
        for (int i = 0; i < m_saveMedium.getNumElectrolyteComponents(); i++) {
            m_mediumToEdit.addElectrolyteComponent(m_saveMedium.getElectrolyteComponentLabel(i), m_saveMedium.getElectrolyteComponentValence(i), m_saveMedium.getElectrolyteComponentConcentration(i));
        }

        setVisible(false);
        m_mediumToEdit = null;
        m_saveMedium = null;
    }//GEN-LAST:event_o_cancelButtonActionPerformed

    private void o_deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_deleteButtonActionPerformed
        if (o_electrolyteTable.getRowCount() > 1) {
            m_mediumToEdit.deleteElectrolyteComponent(o_electrolyteTable.getSelectedRow());
            o_electrolyteTable.updateUI();
            o_deleteButton.setEnabled(o_electrolyteTable.getRowCount() > 0 && o_electrolyteTable.getSelectedRowCount() > 0 && o_electrolyteTable.getSelectedRow() < o_electrolyteTable.getRowCount());
            updateKappa();
        } else {
            JOptionPane.showMessageDialog(this, "Your electrolyte needs to contain at least one species!", "Cannot delete species", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_o_deleteButtonActionPerformed

    private void o_addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_o_addButtonActionPerformed
        m_mediumToEdit.addElectrolyteComponent();
        o_electrolyteTable.updateUI();
        o_deleteButton.setEnabled(o_electrolyteTable.getRowCount() > 0 && o_electrolyteTable.getSelectedRowCount() > 0);
        updateKappa();
    }//GEN-LAST:event_o_addButtonActionPerformed

    private void o_dielectricConstantPropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_o_dielectricConstantPropertyChange
        if (m_mediumToEdit != null) {
            m_mediumToEdit.setDielectricConstantFromText(o_dielectricConstant.getText());
            updateKappa();
        }
    }//GEN-LAST:event_o_dielectricConstantPropertyChange

    private void o_tempPropertyChange(java.beans.PropertyChangeEvent evt) {//GEN-FIRST:event_o_tempPropertyChange
        m_temp = Double.valueOf(o_temp.getText()).doubleValue();
        updateKappa();
    }//GEN-LAST:event_o_tempPropertyChange

