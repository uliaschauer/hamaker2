    @Override
    public void chartMouseMoved(ChartMouseEvent event) {
        
        org.jfree.chart.ChartPanel panel = (org.jfree.chart.ChartPanel)o_paintPanel;
        
        Rectangle2D dataArea = panel.getScreenDataArea();
        JFreeChart chart = event.getChart();
        org.jfree.chart.plot.XYPlot plot = (org.jfree.chart.plot.XYPlot) chart.getPlot();
        org.jfree.chart.axis.ValueAxis xAxis = plot.getDomainAxis();
        double x = xAxis.java2DToValue(event.getTrigger().getX(), dataArea, org.jfree.ui.RectangleEdge.BOTTOM);
        double y = interpolate(m_yodelPlotData.getSeries(0), x);
        m_xCrosshair.setValue(x);
        m_yCrosshair.setValue(y);
    }
    
    private double interpolate(XYSeries s, double x)
    {
        if (x <= s.getMinX())
        {
            return s.getY(0).doubleValue();
        }
        if (x >= s.getMaxX())
        {
            return s.getY(s.getItemCount()-1).doubleValue();
        }
        List<?> items = s.getItems();
        for (int i=0; i<items.size()-1; i++)
        {
            org.jfree.data.xy.XYDataItem i0 = (org.jfree.data.xy.XYDataItem) items.get(i);
            org.jfree.data.xy.XYDataItem i1 = (org.jfree.data.xy.XYDataItem) items.get(i+1);
            double x0 = i0.getXValue();
            double y0 = i0.getYValue();
            double x1 = i1.getXValue();
            double y1 = i1.getYValue();

            if (x >= x0 && x <= x1)
            {
                double d = x - x0;
                double a = d / (x1-x0);
                double y = y0 + a * (y1 - y0);
                return y;
            }
        }
        // Should never happen
        return 0;
    }
