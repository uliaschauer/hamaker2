    private final org.jfree.data.xy.XYSeriesCollection m_yodelPlotData;
    private org.jfree.chart.plot.Crosshair m_xCrosshair, m_yCrosshair;

    private void updatePlot() {
        if (m_editedSerie != null) {
            //m_editedSerie.getYodel().printParams();

            Yodel yodel = m_editedSerie.getYodel();

            m_yodelPlotData.removeAllSeries();
            XYSeries newSerie = new XYSeries("");

            final int kNumPoints = 100;
            double min = yodel.getPercolationTreshold();
            double max = yodel.getMaxPackingFraction();
            double stepSize = (max - min) / ((double) kNumPoints);

            for (int point = 0; point < kNumPoints; point++) {
                double volFrac = min + point * stepSize;
                double yieldStress = yodel.yieldStress(m_editedSerie, volFrac);

                //System.out.println(String.valueOf(volFrac) + ", " + String.valueOf(yieldStress));
                newSerie.add(volFrac, yieldStress);
            }

            m_yodelPlotData.addSeries(newSerie);

            o_paintPanel.repaint();
        }
    }

    private JPanel createPlotPanel() {
        JFreeChart chart = org.jfree.chart.ChartFactory.createXYLineChart(
                null, //title
                "Volume fraction (-)", //x axis label
                "Yield stress (Pa)", //y axis label
                m_yodelPlotData, //data 
                org.jfree.chart.plot.PlotOrientation.VERTICAL, //orientation
                false, //legend
                true, //tootips
                false //URLs
        );
        chart.getPlot().setBackgroundPaint(Color.white);
        
        org.jfree.chart.ChartPanel panel = new org.jfree.chart.ChartPanel(chart,
                400, //width
                200, //height
                50, //min width
                50, //min height
                1000, //max width
                1000, //max height
                false, //buffer
                false, //properties
                false, //save
                false, //print
                false, //zoom
                false); //tooltips

        //create the crosshair
        m_xCrosshair = new org.jfree.chart.plot.Crosshair(Double.NaN, Color.GRAY, new BasicStroke(0f));
        m_yCrosshair = new org.jfree.chart.plot.Crosshair(Double.NaN, Color.GRAY, new BasicStroke(0f));
        m_xCrosshair.setLabelVisible(true);
        m_yCrosshair.setLabelVisible(true);
        
        org.jfree.chart.panel.CrosshairOverlay crosshairs = new org.jfree.chart.panel.CrosshairOverlay();
        crosshairs.addDomainCrosshair(m_xCrosshair); //x axis
        crosshairs.addRangeCrosshair(m_yCrosshair); //y axis
        panel.addOverlay(crosshairs);

        panel.addChartMouseListener(this);

        return panel;
    }    

