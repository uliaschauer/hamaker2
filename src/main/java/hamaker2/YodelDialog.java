    /**
     * Show the dialog for the given series
     *
     * @param s Series to be edited
     */
    public void showForSerie(Serie s) {

        //locally save the serie to be edited
        m_editedSerie = s;

        //make a copy to use when cancelling
        m_saveSerie = Serie.newInstance(s);

        o_percolation.setText(String.valueOf(s.getYodel().getPercolationTreshold()));
        o_maxPack.setText(String.valueOf(s.getYodel().getMaxPackingFraction()));
        o_volumeFunction.setSelectedItem(s.getYodel().getVolumeIncrementFunction());

        o_radiusHarmonic.setSelected(s.getYodel().getHarmonicCurvature());
        o_radiusManual.setSelected(!s.getYodel().getHarmonicCurvature());
        o_contactRadius.setText(String.valueOf(s.getYodel().getCurvatureRadius() * 1E9));
        o_contactRadius.setEnabled(!s.getYodel().getHarmonicCurvature());
        o_harmRadius.setText(new DecimalFormat("0.0").format(s.averageHarmonicRadius() * 1E9));

        o_forceAutomatic.setSelected(s.getYodel().getAutoAttractiveForce());
        o_forceManual.setSelected(!s.getYodel().getAutoAttractiveForce());
        o_autoHamaker.setText(new DecimalFormat("0.00E00").format(s.getYodel().getAutoAttractiveHamaker(s)));
        o_autoSeparation.setText(new DecimalFormat("0.00").format(s.getYodel().getAutoAttractiveSeparation(s) * 1E9));
        o_manualHamaker.setText(new DecimalFormat("0.00E00").format(s.getYodel().getManualAttractiveHamaker()));
        o_manualHamaker.setEnabled(!s.getYodel().getAutoAttractiveForce());
        o_manualSeparation.setText(new DecimalFormat("0.00").format(s.getYodel().getManualAttractiveSeparation() * 1E9));
        o_manualSeparation.setEnabled(!s.getYodel().getAutoAttractiveForce());

        o_volFracSlider.setEnabled(s.getHeterogeneous());
        if (s.getHeterogeneous()) {
            o_volFrac1.setText(new DecimalFormat("0.00").format(s.getYodel().getParticle1VolumeFraction()));
            o_volFrac2.setText(new DecimalFormat("0.00").format(s.getYodel().getParticle2VolumeFraction()));
            o_volFracSlider.setValue((int) (s.getYodel().getParticle2VolumeFraction() * 100));
        } else {
            o_volFracSlider.setValue(0);
            o_volFrac1.setText("1.00");
            o_volFrac2.setText("0.00");
        }

        o_b_tilda_bug.setSelected(s.getYodel().bTildaBug());

        this.setVisible(true);
    }

