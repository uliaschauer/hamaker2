    @Override
    public void mouseDragged(MouseEvent e) {
        if (m_button == MouseEvent.BUTTON1) {

            if ((e.getModifiers() & MouseEvent.ALT_MASK) != 0) {
                //rotate
                m_trackball.mouseDrag(e.getX(), e.getY());
            } else if ((e.getModifiers() & MouseEvent.SHIFT_MASK) != 0) {
                //zoom
                m_scale += 0.01 * (double) (e.getY() - m_dragY);
                if (m_scale < 0.0001) {
                    m_scale = 0.0001;
                }
                m_dragX = e.getX();
                m_dragY = e.getY();
            } else {
                //drag
                m_trans_x += (double) (e.getX() - m_dragX) / (double) (0.1 * this.getWidth());
                m_trans_y += (double) (e.getY() - m_dragY) / (double) (-0.1 * this.getHeight());
                m_dragX = e.getX();
                m_dragY = e.getY();
            }
        } else if (m_button == MouseEvent.BUTTON3) {
            m_trackball.mouseDrag(e.getX(), e.getY());
        }

        o_openGLPanel.repaint();
    }

    @Override
    public void mouseWheelMoved(MouseWheelEvent e) {
        m_scale += 0.1 * e.getWheelRotation();
        if (m_scale < 1) {
            m_scale = 1;
        }
        o_openGLPanel.repaint();
    }

