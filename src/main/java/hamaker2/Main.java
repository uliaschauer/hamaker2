    @Override
    public void mousePressed(MouseEvent e) {

        m_button = e.getButton();

        if (m_button == MouseEvent.BUTTON1) {

            if ((e.getModifiers() & MouseEvent.ALT_MASK) != 0) {
                //rotate
                m_trackball.mouseDown(e.getX(), e.getY());
            } else if ((e.getModifiers() & MouseEvent.SHIFT_MASK) != 0) {
                //zoom
                m_dragX = e.getX();
                m_dragY = e.getY();
            } else {
                //drag
                m_dragX = e.getX();
                m_dragY = e.getY();
            }

        } else if (m_button == MouseEvent.BUTTON3) {
            m_trackball.mouseDown(e.getX(), e.getY());
        }

        o_openGLPanel.repaint();
    }

    @Override
    public void mouseReleased(MouseEvent e) {
        if (e.getButton() == MouseEvent.BUTTON1) {
            if ((e.getModifiers() & MouseEvent.ALT_MASK) != 0) { //rotate
                m_trackball.mouseUp(e.getX(), e.getY());
            }
        }

        if (e.getButton() == MouseEvent.BUTTON3) {
            m_trackball.mouseUp(e.getX(), e.getY());
        }

        m_button = 0;

        o_openGLPanel.repaint();
    }

