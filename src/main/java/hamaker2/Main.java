    private void updatePlotVariables() {

        //save selections
        String savedID1 = m_project.getSelectedVariable1().getID();
        String savedID2 = m_project.getSelectedVariable2().getID();
        int savedIndex1 = o_firstVariable.getSelectedIndex();
        int savedIndex2 = o_secondVariable.getSelectedIndex();

        //rebuild data
        m_project.updatePlotVariables();
        ArrayList<PlotVariable> variables = m_project.getPlotVariables();

        o_firstVariable.setModel(new DefaultComboBoxModel<>(variables.toArray(m_plot1Array)));
        o_secondVariable.setModel(new DefaultComboBoxModel<>(variables.toArray(m_plot2Array)));

        //restore selections
        boolean set = false;
        for (int i = 0; i < variables.size(); i++) {
            if (variables.get(i).getID().equals(savedID1)) {
                set = true;
                o_firstVariable.setSelectedIndex(i);
            }
        }
        if (!set) {
            o_firstVariable.setSelectedIndex(savedIndex1);
        }

        set = false;
        for (int i = 0; i < variables.size(); i++) {
            if (variables.get(i).getID().equals(savedID2)) {
                set = true;
                o_secondVariable.setSelectedIndex(i);
            }
        }
        if (!set) {
            o_secondVariable.setSelectedIndex(savedIndex2);
        }
    }

