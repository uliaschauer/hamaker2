    private class ColorChooserResponder implements ActionListener {

        JColorChooser m_colorChooser;
        JDialog m_dialog;
        String m_type;

        public ColorChooserResponder(String type) {
            m_colorChooser = new JColorChooser();
            m_type = type;
            if (m_type.equals("FILL")) {
                m_colorChooser.setColor(m_project.getSelectedSerie().getColor());
            } else {
                m_colorChooser.setColor(m_project.getSelectedSerie().getGridColor());
            }
            m_dialog = JColorChooser.createDialog(null, "Pick a Color", true, m_colorChooser, this, null);
            m_dialog.setVisible(true);
        }

        @Override
        public void actionPerformed(ActionEvent evt) {
            if (m_type.equals("FILL")) {
                m_project.getSelectedSerie().setColor(m_colorChooser.getColor());
            } else {
                m_project.getSelectedSerie().setGridColor(m_colorChooser.getColor());
            }
        }
    }
